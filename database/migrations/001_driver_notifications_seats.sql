ALTER TABLE `users` ADD COLUMN IF NOT EXISTS `duty` TINYINT(1) NOT NULL DEFAULT 1;

ALTER TABLE `trips`
  ADD COLUMN IF NOT EXISTS `seats` SMALLINT UNSIGNED NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `seats_at` DATETIME NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `prev_depart` TIME NULL DEFAULT NULL,
  ADD COLUMN IF NOT EXISTS `unmet` SMALLINT UNSIGNED NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS `notifications` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `user_id` INT UNSIGNED NOT NULL,
  `title` VARCHAR(100) NOT NULL,
  `body` VARCHAR(300) NOT NULL DEFAULT '',
  `tag` VARCHAR(20) NOT NULL DEFAULT 'Update',
  `is_read` TINYINT(1) NOT NULL DEFAULT 0,
  `created_at` TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
  KEY `user_read` (`user_id`, `is_read`, `id`),
  CONSTRAINT `notifications_ibfk_1` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
